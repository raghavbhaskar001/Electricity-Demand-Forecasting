    h += `</tr><tr><th style="background:transparent"></th>`;
    for (const a of ARCHS) for (const f of FEATS) h += `<th style="text-align:center;background:transparent;font-size:9.5px;letter-spacing:.04em" title="${esc(FEAT[f])}">${FEAT_SHORT[f]}</th>`;
    h += "</tr></thead><tbody>";
    for (const s of SCALES) for (const d of DISTS) {
      h += `<tr><td style="font-size:12px"><b style="font-weight:580">${SCALE[s]}</b> <span class="muted">${DIST[d]}</span></td>`;
      for (const a of ARCHS) for (const f of FEATS) {
        const e = byId[expId(s, d, a, f)], v = e && e.metrics ? e.metrics.persistence_skill_score : null;
        h += `<td style="padding:3px"><div title="${esc(e ? e.id : "")}" style="${cell(v)};border:1px solid;border-radius:7px;padding:7px 2px;text-align:center;font-family:var(--mono);font-size:11px">${pctSigned(v)}</div></td>`;
      }
      h += "</tr>";
    }
    h += "</tbody></table></div>";
    $("#skill-map").innerHTML = h;

    // Findings — generated from DM table + metrics
    const F = [];
    for (const d of DISTS) {
      const row = D.dm_tests.find(r => r.district === d && r.category === "Deep Learning vs Baseline");
      if (row) F.push({ c: "amber", t: `${DIST[d]} aggregate: persistence beat the best DL model`, d: `${row.model_1} vs ${row.model_2}: DM = ${fx(row.dm_stat, 2)}, Holm p ${pfmt(row.p_adj)} (n = ${int(row.n)}).` });
    }
    const sig = D.dm_tests.filter(r => r.significant).length;
