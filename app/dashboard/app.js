  // ------------------------------------------------------------------ format
  function fx(v, d) { return v == null || Number.isNaN(v) ? "—" : Number(v).toFixed(d); }
  function pctSigned(v) { if (v == null) return "—"; const p = v * 100; return (p > 0 ? "+" : "") + p.toFixed(2) + "%"; }
  function int(v) { return v == null ? "—" : Number(v).toLocaleString("en-IN"); }
  function pfmt(p) { if (p == null) return "—"; if (p === 0) return "< 1e-15"; if (p < 1e-3) return p.toExponential(2); return p.toFixed(4); }
  function esc(s) { return String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c])); }
  const $ = s => document.querySelector(s);

  function statusBadge(e) {
    const s = e.validation_status || "";
    if (/^VALIDATED/i.test(s)) return '<span class="badge b-ok" title="' + esc(s) + '">DM-validated</span>';
    if (/PENDING/i.test(s)) return '<span class="badge b-warn" title="' + esc(s) + '">Descriptive · panel test pending</span>';
    return '<span class="badge b-info">' + esc(s || "Status not recorded") + "</span>";
  }

  // ------------------------------------------------------------------ math
  function lin(d0, d1, r0, r1) {
    const k = (r1 - r0) / ((d1 - d0) || 1);
    const f = v => r0 + (v - d0) * k;
    f.inv = p => d0 + (p - r0) / k;
    return f;
  }
  function niceStep(range, n) {
    const raw = range / Math.max(1, n), mag = Math.pow(10, Math.floor(Math.log10(raw || 1))), r = raw / mag;
    return (r >= 5 ? 10 : r >= 2 ? 5 : r >= 1 ? 2 : 1) * mag;
  }
  function ticks(min, max, n = 5) {
    if (min === max) { min -= 1; max += 1; }
    const s = niceStep(max - min, n), out = [];
    for (let v = Math.ceil(min / s) * s; v <= max + s * 1e-9; v += s) out.push(+v.toFixed(10));
    return out;
  }
  function extent(arrs) {
    let lo = Infinity, hi = -Infinity;
    for (const a of arrs) for (const v of a) if (v != null && isFinite(v)) { if (v < lo) lo = v; if (v > hi) hi = v; }
    return [lo, hi];
  }
  const rmse = (a, p) => { let s = 0; for (let i = 0; i < a.length; i++) s += (a[i] - p[i]) ** 2; return Math.sqrt(s / a.length); };
  const mae = (a, p) => { let s = 0; for (let i = 0; i < a.length; i++) s += Math.abs(a[i] - p[i]); return s / a.length; };
  const bias = (a, p) => { let s = 0; for (let i = 0; i < a.length; i++) s += p[i] - a[i]; return s / a.length; };

