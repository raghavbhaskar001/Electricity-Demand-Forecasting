  const TT = $("#tooltip");
  function showTT(html, x, y) {
    TT.innerHTML = html; TT.classList.add("show");
    const w = TT.offsetWidth, h = TT.offsetHeight;
    let left = x + 14, top = y - h - 10;
    if (left + w > window.innerWidth - 8) left = x - w - 14;
    if (top < 8) top = y + 14;
    TT.style.left = left + window.scrollX + "px"; TT.style.top = top + window.scrollY + "px";
  }
  const hideTT = () => TT.classList.remove("show");
  const ttRow = (k, v, color) => `<div class="tt-r"><span>${color ? `<i style="display:inline-block;width:8px;height:8px;border-radius:2px;background:${color};margin-right:6px"></i>` : ""}${k}</span><span>${v}</span></div>`;

  // ------------------------------------------------------------------ charts
  /** Index-based multi-line chart; breaks the line where the series has time gaps. */
  function lineChart(el, o) {
    const W = el.clientWidth || 600, H = o.height || 300, P = { l: 52, r: 14, t: 10, b: 28 };
    const n = o.n, x = lin(0, Math.max(1, n - 1), P.l, W - P.r);
    let [lo, hi] = extent(o.series.map(s => s.values));
    const pad = (hi - lo) * 0.06 || 1; lo -= pad; hi += pad;
    const yt = ticks(lo, hi, 5), y = lin(yt[0], yt[yt.length - 1], H - P.b, P.t);
    let svg = `<svg viewBox="0 0 ${W} ${H}" height="${H}" role="img" aria-label="${esc(o.aria || "Line chart")}">`;
    svg += '<g class="axis">';
    for (const t of yt) svg += `<line class="gridline" x1="${P.l}" x2="${W - P.r}" y1="${y(t)}" y2="${y(t)}"/><text x="${P.l - 8}" y="${y(t) + 3.5}" text-anchor="end">${t.toFixed(o.yDec ?? 1)}</text>`;
    const nt = Math.min(7, n), step = Math.max(1, Math.floor((n - 1) / Math.max(1, nt - 1)));
    for (let i = 0; i < n; i += step) svg += `<text x="${x(i)}" y="${H - 8}" text-anchor="middle">${esc(o.xLabel(i))}</text>`;
    svg += `<text class="axis-title" transform="translate(12 ${(H - P.b + P.t) / 2}) rotate(-90)" text-anchor="middle">${esc(o.yTitle)}</text>`;
    svg += "</g>";
    for (const b of o.breaks || []) if (b > 0 && b < n) svg += `<line x1="${(x(b - 1) + x(b)) / 2}" x2="${(x(b - 1) + x(b)) / 2}" y1="${P.t}" y2="${H - P.b}" stroke="rgba(148,163,184,0.22)" stroke-dasharray="2 3"/>`;
    const brk = new Set(o.breaks || []);
    for (const s of o.series) {
      let d = "";
      s.values.forEach((v, i) => { d += (i === 0 || brk.has(i) ? "M" : "L") + x(i).toFixed(1) + " " + y(v).toFixed(1); });
      svg += `<path class="line" d="${d}" stroke="${s.color}" ${s.dash ? `stroke-dasharray="${s.dash}"` : ""} stroke-width="${s.width || 1.6}" opacity="${s.opacity || 1}"/>`;
    }
    svg += `<line id="xh" y1="${P.t}" y2="${H - P.b}" stroke="rgba(241,245,249,0.35)" visibility="hidden"/>`;
    o.series.forEach((s, k) => { svg += `<circle data-k="${k}" r="3.2" fill="${s.color}" stroke="#071321" stroke-width="1.5" visibility="hidden"/>`; });
    svg += `<rect x="${P.l}" y="${P.t}" width="${W - P.l - P.r}" height="${H - P.t - P.b}" fill="transparent"/></svg>`;
    el.innerHTML = svg;
    const root = el.querySelector("svg"), rect = root.querySelector("rect:last-of-type"), xh = root.querySelector("#xh"), dots = root.querySelectorAll("circle");
    rect.addEventListener("mousemove", ev => {
      const bb = root.getBoundingClientRect(), px = (ev.clientX - bb.left) * (W / bb.width);
      const i = Math.max(0, Math.min(n - 1, Math.round(x.inv(px))));
      xh.setAttribute("x1", x(i)); xh.setAttribute("x2", x(i)); xh.setAttribute("visibility", "visible");
      dots.forEach((c, k) => { c.setAttribute("cx", x(i)); c.setAttribute("cy", y(o.series[k].values[i])); c.setAttribute("visibility", "visible"); });
      showTT(o.tooltip(i), ev.clientX, ev.clientY);
    });
    rect.addEventListener("mouseleave", () => { xh.setAttribute("visibility", "hidden"); dots.forEach(c => c.setAttribute("visibility", "hidden")); hideTT(); });
  }

  /** Vertical bars, supports negative values and an optional baseline. */
  function barChart(el, o) {
    const W = el.clientWidth || 600, H = o.height || 240, P = { l: 52, r: 14, t: 12, b: o.xLabels ? 30 : 12 };
    const vals = o.values, n = vals.length;
    let [lo, hi] = extent([vals, o.baseline != null ? [o.baseline] : [], [0]]);
    const pad = (hi - lo) * 0.06 || 1; if (lo < 0) lo -= pad; hi += hi > 0 ? pad : 0;
    const yt = ticks(lo, hi, 5), y = lin(yt[0], yt[yt.length - 1], H - P.b, P.t);
    const bw = (W - P.l - P.r) / n, gap = Math.min(bw * 0.25, 4);
    let svg = `<svg viewBox="0 0 ${W} ${H}" height="${H}" role="img" aria-label="${esc(o.aria || "Bar chart")}"><g class="axis">`;
    for (const t of yt) svg += `<line class="gridline" x1="${P.l}" x2="${W - P.r}" y1="${y(t)}" y2="${y(t)}"/><text x="${P.l - 8}" y="${y(t) + 3.5}" text-anchor="end">${o.yFmt ? o.yFmt(t) : t}</text>`;
    svg += `<text class="axis-title" transform="translate(12 ${(H - P.b + P.t) / 2}) rotate(-90)" text-anchor="middle">${esc(o.yTitle || "")}</text>`;
    if (o.xLabels) { const every = Math.ceil(n / 24); o.xLabels.forEach((l, i) => { if (i % every === 0) svg += `<text x="${P.l + bw * (i + 0.5)}" y="${H - 10}" text-anchor="middle">${esc(l)}</text>`; }); }
    svg += `</g><line x1="${P.l}" x2="${W - P.r}" y1="${y(0)}" y2="${y(0)}" stroke="rgba(241,245,249,0.25)"/>`;
    vals.forEach((v, i) => {
      if (v == null) return;
      const y0 = y(0), y1 = y(v);
      svg += `<rect class="bar-rect" data-i="${i}" x="${P.l + bw * i + gap / 2}" y="${Math.min(y0, y1)}" width="${Math.max(1, bw - gap)}" height="${Math.max(1, Math.abs(y1 - y0))}" rx="${bw > 8 ? 2 : 0}" fill="${o.color(v, i)}"/>`;
    });
    if (o.baseline != null) svg += `<line x1="${P.l}" x2="${W - P.r}" y1="${y(o.baseline)}" y2="${y(o.baseline)}" stroke="#F1F5F9" stroke-dasharray="5 4" opacity=".7"/><text x="${W - P.r}" y="${y(o.baseline) - 5}" text-anchor="end" fill="#94A3B8" font-size="10.5">${esc(o.baselineLabel || "")}</text>`;
    svg += "</svg>";
    el.innerHTML = svg;
    if (o.tooltip) el.querySelectorAll("rect.bar-rect").forEach(r => {
      r.addEventListener("mousemove", ev => showTT(o.tooltip(+r.dataset.i), ev.clientX, ev.clientY));
      r.addEventListener("mouseleave", hideTT);
    });
  }

  /** Grouped bars (groups × series) with dashed persistence baseline. */
  function groupedChart(el, o) {
    const W = el.clientWidth || 600, H = o.height || 310, P = { l: 56, r: 14, t: 18, b: 42 };
    const all = []; o.groups.forEach(g => o.series.forEach(s => { const v = o.value(g, s); if (v != null) all.push(v); }));
    let [lo, hi] = extent([all, o.baseline != null ? [o.baseline] : [], [0]]);
    const pad = (hi - lo) * 0.10 || 1; if (lo < 0) lo -= pad; hi += hi > 0 ? pad : pad * 0.2;
    const yt = ticks(lo, hi, 5), y = lin(yt[0], yt[yt.length - 1], H - P.b, P.t);
    const gw = (W - P.l - P.r) / o.groups.length, inner = gw * 0.7, bw = inner / o.series.length;
    let svg = `<svg viewBox="0 0 ${W} ${H}" height="${H}" role="img" aria-label="${esc(o.aria || "Grouped bar chart")}"><defs>`;
    o.series.forEach((s, k) => { svg += `<linearGradient id="gb${k}" x1="0" x2="0" y1="0" y2="1"><stop offset="0" stop-color="${s.color}" stop-opacity=".95"/><stop offset="1" stop-color="${s.color}" stop-opacity=".45"/></linearGradient>`; });
    svg += '</defs><g class="axis">';
    for (const t of yt) svg += `<line class="gridline" x1="${P.l}" x2="${W - P.r}" y1="${y(t)}" y2="${y(t)}"/><text x="${P.l - 8}" y="${y(t) + 3.5}" text-anchor="end">${o.yFmt(t)}</text>`;
    o.groups.forEach((g, gi) => { svg += `<text x="${P.l + gw * (gi + 0.5)}" y="${H - 10}" text-anchor="middle" style="font-family:var(--sans);font-size:11.5px;fill:#94A3B8">${esc(o.groupLabel(g))}</text>`; });
    svg += `<text class="axis-title" transform="translate(12 ${(H - P.b + P.t) / 2}) rotate(-90)" text-anchor="middle">${esc(o.yTitle)}</text></g>`;
    svg += `<line x1="${P.l}" x2="${W - P.r}" y1="${y(0)}" y2="${y(0)}" stroke="rgba(241,245,249,0.25)"/>`;
    o.groups.forEach((g, gi) => o.series.forEach((s, si) => {
      const v = o.value(g, s); if (v == null) return;
      const bx = P.l + gw * gi + (gw - inner) / 2 + bw * si, y0 = y(0), y1 = y(v);
      const ly = v >= 0 ? Math.max(P.t + 8, y1 - 5) : Math.min(H - P.b + 11, y1 + 12);
      svg += `<rect class="bar-rect" data-g="${gi}" data-s="${si}" x="${bx + 2}" y="${Math.min(y0, y1)}" width="${Math.max(2, bw - 4)}" height="${Math.max(1, Math.abs(y1 - y0))}" rx="3" fill="url(#gb${si})" stroke="${s.color}" stroke-opacity=".6"/>`;
      svg += `<text x="${bx + bw / 2}" y="${ly}" text-anchor="middle" fill="#CBD5E1" font-size="10" font-family="var(--mono)">${o.labelFmt(v)}</text>`;
    }));
    if (o.baseline != null) svg += `<line x1="${P.l}" x2="${W - P.r}" y1="${y(o.baseline)}" y2="${y(o.baseline)}" stroke="#F1F5F9" stroke-dasharray="6 4" opacity=".75"/><text x="${W - P.r}" y="${y(o.baseline) - 6}" text-anchor="end" fill="#E2E8F0" font-size="10.5">${esc(o.baselineLabel)}</text>`;
    svg += "</svg>";
    el.innerHTML = svg;
    el.querySelectorAll("rect.bar-rect").forEach(r => {
      r.addEventListener("mousemove", ev => showTT(o.tooltip(o.groups[+r.dataset.g], o.series[+r.dataset.s]), ev.clientX, ev.clientY));
      r.addEventListener("mouseleave", hideTT);
    });
  }

